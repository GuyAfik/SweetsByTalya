export const getFeaturedProducts = () => products.filter(p => p.featured && p.available)
export const getProductsByCategory = (category) =>
  category === 'all' ? products.filter(p => p.available) : products.filter(p => p.category === category && p.available)

// Menu summary for AI chatbot system prompt
export const getMenuSummaryForAI = () => {
  return products
    .filter(p => p.available)
    .map(p => `- ${p.name}: ${p.description}. Price: ${p.price ? `${p.price}${p.currency} ${p.unit}` : 'Price on request'}. Ingredients: ${p.ingredients.join(', ')}. Allergens: ${p.allergens.join(', ') || 'none'}.`)
    .join('\n')
}
